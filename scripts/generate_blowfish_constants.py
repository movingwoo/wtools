#!/usr/bin/env python3
"""Generate Blowfish's 1042 public pi words using Machin's formula, no dependencies.

Algorithm parameters: https://www.schneier.com/academic/blowfish/
These are mathematical constants, not a copied third-party implementation.
"""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / 'js/lib/crypto/blowfish-constants.js'


def pi_words(guard=128):
    bits = 1042 * 32
    scale = 1 << (bits + guard)

    def arctan(reciprocal):
        term, value, denominator, sign = scale // reciprocal, 0, 1, 1
        while term:
            value += sign * (term // denominator)
            term //= reciprocal * reciprocal
            denominator += 2
            sign = -sign
        return value

    fraction = ((16 * arctan(5) - 4 * arctan(239)) >> guard) - (3 << bits)
    return [(fraction >> ((1041 - i) * 32)) & 0xffffffff for i in range(1042)]


def source():
    words = pi_words()
    assert words[:2] == [0x243f6a88, 0x85a308d3]
    assert words == pi_words(192), 'Guard precision changed a pi digit'
    rows = ['  ' + ', '.join(f'0x{word:08x}' for word in words[i:i + 8]) + ','
            for i in range(0, len(words), 8)]
    return ('// Fractional hexadecimal digits of pi. Generated by scripts/generate_blowfish_constants.py.\n'
            'export const PI_WORDS = new Uint32Array([\n' + '\n'.join(rows) + '\n]);\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = source()
    if args.check:
        if TARGET.read_text() != expected:
            raise SystemExit('Blowfish pi constants are stale')
    else:
        TARGET.write_text(expected)
